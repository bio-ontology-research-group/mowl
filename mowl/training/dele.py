"""Training regimes of DELE [mashkova2024dele]_ and its NeSy 2024 predecessor
[mashkova2024nesy]_.

DELE is not an embedding method. It is a way to train (and to evaluate) any geometric
:math:`\\mathcal{EL}^{++}` embedding with the help of the deductive closure. Its training
part consists of two independent pieces, implemented here as two composable
:class:`~mowl.training.TrainingRegime` objects:

- :class:`AllNormalFormNegatives`: sample negatives for all seven normal forms and train
  them with the negative losses of DELE, Section 4 (the "+l" models of DELE, Tables 3-6);
- :class:`ClosureFilteredNegatives`: never use an entailed axiom as a negative (DELE,
  Section 5; the "+n" models). It is a pure ``filter_negatives`` regime, so it works with
  any negative sampler: the model's own, :class:`AllNormalFormNegatives`, or the regime of
  another paper.

:func:`dele_regime` composes them into the regime of the "+l+n" rows of DELE's tables.

:class:`ClosurePositives` (deductive-closure axioms as additional training positives) is
*not* part of either paper; it is provided because the closure makes it cheap, and is
documented as an mOWL extension.

Example::

    model = ELEmbeddings(dataset)
    model.training_regime = dele_regime()           # ELEm+l+n
    model.train(epochs=100)
"""

import logging

import torch as th
import numpy as np

from mowl.training.regime import TrainingRegime, ComposedRegime
from mowl.training.closure import DeductiveClosure, NORMAL_FORMS

logger = logging.getLogger(__name__)

#: Column corrupted for each normal form when DELE samples a negative (see the reference
#: implementation and DELE, Section 4.1: "we vary only the E part of GCI1 axioms"). The
#: GCI0/GCI1/GCI2/GCI3 columns agree with the defaults of
#: :class:`~mowl.base_models.elmodel.EmbeddingELModel`.
DELE_CORRUPT_COLUMN = {
    "gci0": 1,      # A ⊑ B'
    "gci1": 2,      # A ⊓ B ⊑ E'
    "gci2": 2,      # A ⊑ ∃r.B'
    "gci3": 2,      # ∃r.A ⊑ B'
    "gci0_bot": 0,  # A' ⊑ ⊥
    "gci1_bot": 0,  # A' ⊓ B ⊑ ⊥
    "gci3_bot": 1,  # ∃r.A' ⊑ ⊥
}

#: Columns holding role indices, per normal form (all other columns hold classes).
ROLE_COLUMNS = {"gci2": (1,), "gci3": (0,), "gci3_bot": (0,)}


def _pool(model, gci_name, column):
    if column in ROLE_COLUMNS.get(gci_name, ()):
        return np.fromiter(model.object_property_index_dict.values(), dtype=np.int64)
    return np.fromiter(model.named_class_index_dict.values(), dtype=np.int64)


def _corrupt(data, column, pool, device):
    idx = np.random.choice(pool, size=len(data), replace=True)
    out = data.clone()
    out[:, column] = th.tensor(idx, dtype=out.dtype, device=device)
    return out


class _Closure:
    """Mixin: a deductive closure given explicitly or computed from the model on first
    use."""

    def _init_closure(self, closure, reasoner, cache_dir):
        if closure is not None and not isinstance(closure, DeductiveClosure):
            raise TypeError("closure must be a mowl.training.DeductiveClosure or None.")
        self._closure = closure
        self.reasoner = reasoner
        self.cache_dir = cache_dir

    @property
    def closure(self):
        """The :class:`~mowl.training.DeductiveClosure` used (computed from the model's
        training ontology on first access if none was given)."""
        if self._closure is None:
            if self.model is None:
                raise RuntimeError("The regime is not attached to a model yet.")
            self._closure = DeductiveClosure.from_model(self.model, reasoner=self.reasoner,
                                                        cache_dir=self.cache_dir)
        return self._closure


class AllNormalFormNegatives(TrainingRegime):
    """Negatives and negative losses for all seven :math:`\\mathcal{EL}^{++}` normal forms
    (DELE, Section 4; NeSy 2024, Section 4.2).

    On :meth:`attach` the module's DELE negative losses are switched on
    (``enable_all_negative_losses``, available on :class:`~mowl.nn.ELEmModule`,
    :class:`~mowl.nn.ELBEModule` and :class:`~mowl.nn.BoxSquaredELModule`); any other module
    must already declare all seven normal forms in ``neg_capable_gcis``.

    Negatives are generated by corrupting one column (:data:`DELE_CORRUPT_COLUMN`) with an
    entity drawn uniformly from the model's named classes (or object properties for a role
    column). For the normal forms that the model's own negative sampling configuration
    already covers, the model's sampler is used unchanged (``negatives`` returns
    ``NotImplemented``), so a model's own scheme for GCI2 (e.g. TransBox corrupting both
    sides) is kept.

    :param epsilon: :math:`\\varepsilon` of the bottom negative losses, or ``None`` to keep
        the module's value (default ``0.01``).
    :type epsilon: float, optional
    :param normal_forms: Normal forms to sample negatives for. Defaults to all seven.
    :type normal_forms: iterable of str, optional

    .. note:: The reference implementation samples the corrupting class from the dataset's
       evaluation classes; mOWL samples from all named classes, as its default sampler does.
    """

    key = "dele-all-normal-form-negatives"

    def __init__(self, epsilon=None, normal_forms=NORMAL_FORMS):
        super().__init__()
        self.epsilon = epsilon
        self.normal_forms = tuple(normal_forms)
        for nf in self.normal_forms:
            if nf not in DELE_CORRUPT_COLUMN:
                raise ValueError(f"Unknown normal form {nf!r}.")

    def _enable(self):
        module = self.model.module
        if hasattr(module, "enable_all_negative_losses"):
            if not getattr(module, "all_negative_losses", False) or self.epsilon is not None:
                module.enable_all_negative_losses(epsilon=self.epsilon)
        missing = set(self.normal_forms) - set(module.neg_capable_gcis)
        if missing:
            raise TypeError(
                f"{type(module).__name__} has no negative loss for {sorted(missing)}; "
                f"AllNormalFormNegatives needs a module implementing the DELE negative "
                f"losses (ELEmModule, ELBEModule, BoxSquaredELModule).")

    def attach(self, model):
        super().attach(model)
        if getattr(model, "module", None) is None:
            raise TypeError("AllNormalFormNegatives needs a model with a module.")
        self._enable()

    def on_epoch_start(self, epoch, epochs):
        # The module may have been rebuilt (init_module) since attach.
        if not set(self.normal_forms) <= set(self.model.module.neg_capable_gcis):
            self._enable()

    def negatives(self, gci_name, gci_dataset):
        if gci_name not in self.normal_forms:
            return NotImplemented
        if gci_name in self.model.get_negative_sampling_config():
            return NotImplemented
        data = gci_dataset[:]
        column = DELE_CORRUPT_COLUMN[gci_name]
        return _corrupt(data, column, _pool(self.model, gci_name, column), data.device)


class ClosureFilteredNegatives(_Closure, TrainingRegime):
    """Filter entailed axioms out of the sampled negatives (DELE, Section 5; NeSy 2024,
    Section 4.3 "Negatives Filtration").

    A pure ``filter_negatives`` regime: it accepts negatives from any sampler. A negative
    that is in the deductive closure (:class:`~mowl.training.DeductiveClosure`) is
    replaced by re-sampling its corrupted column (from the model's named classes, or
    object properties for a role column) up to ``max_resample`` times. The corrupted column
    of a row is the single column in which it differs from the positive it was derived from
    (the ``i``-th negative row comes from positive ``i mod n``, as in
    :meth:`~mowl.base_models.elmodel.EmbeddingELModel.generate_negatives`); if the row
    equals its positive the column of :data:`DELE_CORRUPT_COLUMN` is used.

    Rows that are still entailed after ``max_resample`` attempts, and rows whose corrupted
    column cannot be identified (more than one column differs, or the number of negatives
    is not a multiple of the number of positives), are **dropped**, which is what the
    papers do with every entailed negative. The number of negative rows can therefore be
    smaller than requested; if none is left, ``None`` is returned (no negative loss for this
    normal form in this epoch). mOWL's losses average negatives separately from positives,
    so they accept this. Counters :attr:`num_entailed` and :attr:`num_dropped` record what
    happened.

    Negatives of axiom types that are not normal forms (class and role assertions) pass
    unchanged.

    :param closure: Precomputed closure in the model's index space, or ``None`` to compute
        it from the model's training ontology on first use.
    :type closure: :class:`~mowl.training.DeductiveClosure`, optional
    :param reasoner: Reasoner for a closure computed here (``"canonical"`` or ``"elk"``).
    :type reasoner: str, optional
    :param max_resample: Number of re-sampling rounds for entailed negatives. ``0`` drops
        them immediately, as in the papers. Defaults to ``10``.
    :type max_resample: int, optional
    :param cache_dir: Cache directory for a closure computed here.
    :type cache_dir: str, optional

    .. note:: The papers delete entailed negatives without replacement; re-sampling
       (``max_resample > 0``, the default) keeps the number of negatives close to the number
       of positives, as the regime interface asks. Both satisfy the property that no
       entailed axiom is ever used as a negative.
    """

    key = "dele-closure-filtered-negatives"

    def __init__(self, closure=None, reasoner="canonical", max_resample=10, cache_dir=None):
        super().__init__()
        self._init_closure(closure, reasoner, cache_dir)
        if int(max_resample) < 0:
            raise ValueError("max_resample must be >= 0.")
        self.max_resample = int(max_resample)
        self.num_entailed = 0
        self.num_dropped = 0

    def filter_negatives(self, gci_name, gci_dataset, negatives):
        if negatives is None or gci_name not in NORMAL_FORMS or len(negatives) == 0:
            return negatives
        closure = self.closure
        entailed = closure.contains(gci_name, negatives)
        if not entailed.any():
            return negatives
        self.num_entailed += int(entailed.sum())

        negatives = negatives.clone()
        positives = gci_dataset[:]
        n = len(positives)
        keep = ~entailed
        bad = th.nonzero(entailed).flatten().tolist()
        columns = {}
        if n > 0 and len(negatives) % n == 0:
            for i in bad:
                diff = th.nonzero(negatives[i] != positives[i % n]).flatten().tolist()
                if len(diff) == 1:
                    columns[i] = diff[0]
                elif len(diff) == 0:
                    columns[i] = DELE_CORRUPT_COLUMN[gci_name]
        pending = [i for i in bad if i in columns]
        for _ in range(self.max_resample):
            if not pending:
                break
            still = []
            for i in pending:
                col = columns[i]
                pool = _pool(self.model, gci_name, col)
                negatives[i, col] = int(np.random.choice(pool))
                if closure.entails(gci_name, negatives[i].tolist()):
                    still.append(i)
                else:
                    keep[i] = True
            pending = still
        dropped = int((~keep).sum())
        self.num_dropped += dropped
        if dropped:
            logger.debug("%s: dropped %d entailed negatives", gci_name, dropped)
        out = negatives[keep]
        return out if len(out) > 0 else None


class ClosurePositives(_Closure, TrainingRegime):
    """Add axioms of the deductive closure to the training data as positives.

    .. warning:: This is **not** part of DELE or of the NeSy 2024 paper, which use the
       closure only to filter negatives and in evaluation. It is an mOWL extension provided
       for experimentation.

    Entailed, non-trivial axioms of the chosen normal forms (see
    :meth:`~mowl.training.DeductiveClosure.axioms`) that are not already training axioms
    are appended to the corresponding training datasets, once, when :meth:`train` starts.

    :param closure: Precomputed closure in the model's index space, or ``None``.
    :param normal_forms: Normal forms to augment, among ``"gci0"``, ``"gci2"``,
        ``"gci3"``. Defaults to ``("gci0", "gci2")``.
    :param heads: Restrict the subclass (filler for gci3) of added axioms to these class
        indices, e.g. the evaluation classes. ``None`` (default) means all named classes.
    :param relations: Restrict the roles of added gci2/gci3 axioms.
    :param max_axioms: Per normal form, keep at most this many added axioms (a uniform
        random subset). ``None`` keeps all.
    :param reasoner: Reasoner for a closure computed here.
    :param cache_dir: Cache directory for a closure computed here.
    """

    key = "closure-positives"

    def __init__(self, closure=None, normal_forms=("gci0", "gci2"), heads=None,
                 relations=None, max_axioms=None, reasoner="canonical", cache_dir=None):
        super().__init__()
        self._init_closure(closure, reasoner, cache_dir)
        for nf in normal_forms:
            if nf not in ("gci0", "gci2", "gci3"):
                raise ValueError("ClosurePositives augments 'gci0', 'gci2' and 'gci3' only.")
        self.normal_forms = tuple(normal_forms)
        self.heads = heads
        self.relations = relations
        self.max_axioms = max_axioms
        self._augmented = None
        self._source = None
        self.num_added = {}

    def training_datasets(self, datasets):
        if self._augmented is not None and self._source is datasets:
            return self._augmented
        heads = self.heads
        if heads is None:
            heads = list(self.model.named_class_index_dict.values())
        out = dict(datasets)
        for nf in self.normal_forms:
            extra = self.closure.axioms(nf, heads=heads, relations=self.relations)
            existing = datasets.get(nf)
            if existing is not None and len(existing) > 0:
                present = {tuple(r) for r in existing[:].tolist()}
                rows = [r for r in extra.tolist() if tuple(r) not in present]
                device = existing[:].device
            else:
                rows = extra.tolist()
                device = self.model.device
            if self.max_axioms is not None and len(rows) > self.max_axioms:
                pick = np.random.choice(len(rows), size=self.max_axioms, replace=False)
                rows = [rows[i] for i in sorted(pick)]
            self.num_added[nf] = len(rows)
            if not rows:
                continue
            added = th.tensor(rows, dtype=th.long, device=device)
            base = existing[:] if existing is not None and len(existing) > 0 else None
            data = added if base is None else th.cat([base, added], dim=0)
            out[nf] = TensorAxiomDataset(data)
        self._source = datasets
        self._augmented = out
        return out


class TensorAxiomDataset(th.utils.data.Dataset):
    """Minimal dataset over an index tensor, with the interface of
    :class:`mowl.datasets.gci.GCIDataset` used by the training loop (``data``, ``[:]``,
    ``len``)."""

    def __init__(self, data):
        super().__init__()
        self._data = data

    @property
    def data(self):
        return self._data

    def __getitem__(self, idx):
        return self._data[idx]

    def __len__(self):
        return len(self._data)


def dele_regime(closure=None, epsilon=None, filter_negatives=True, reasoner="canonical",
                max_resample=10, cache_dir=None):
    """The DELE training regime: negatives and negative losses for all normal forms
    ("+l") and, if ``filter_negatives`` is ``True``, filtering of entailed negatives ("+n").
    ``dele_regime()`` reproduces the "+l+n" rows of DELE's Tables 3-6 and
    ``dele_regime(filter_negatives=False)`` the "+l" rows.

    :rtype: :class:`~mowl.training.ComposedRegime`
    """
    regimes = [AllNormalFormNegatives(epsilon=epsilon)]
    if filter_negatives:
        regimes.append(ClosureFilteredNegatives(closure=closure, reasoner=reasoner,
                                                max_resample=max_resample,
                                                cache_dir=cache_dir))
    return ComposedRegime(*regimes)
