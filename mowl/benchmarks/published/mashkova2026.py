def _results():
    out = []
    for bench, subset, table, cols, rows in _TABLES:
        for model, vals in rows.items():
            assert len(vals) == len(cols), (table, model)
            std = ", ".join(f"{c} ± {s:.2f}" for c, (_, s) in zip(cols, vals))
            out.append(PublishedResult(
                benchmark=bench, method=_NAMES[model],
                metrics={c: m for c, (m, _) in zip(cols, vals)},
                source=MASHKOVA2026, locator=table, subset=subset,
                note=f"Mean over seeds; standard deviations: {std}."))
    return out


RESULTS = _results()
