"""The subsumption-prediction and deductive-reasoning evaluation of Box\\ :sup:`2`\\ EL
(Jackermeier, Chen, Horrocks, WWW 2024, Section 4.2 "Evaluation protocol", Section 4.4,
Appendices F and G), as reusable evaluation regimes.
"""

import numpy as np
import torch as th

from mowl.evaluation.regime import EvaluationRegime
from mowl.evaluation.axiom_ranking import el_rows, candidate_indices, rank_queries
from mowl.evaluation.el_scoring import resolve_scorer
from mowl.evaluation.ranking_metrics import summarise_ranks

#: For every normal form: (column whose entity is ranked, columns whose entity is removed
#: from its own candidate list). Taken from the reference implementation
#: (``evaluate.py``, ``compute_nf*_ranks``): NF1 ``C ⊑ ?D`` excluding ``C``;
#: NF2 ``C ⊓ D ⊑ ?E`` excluding ``C`` and ``D``; NF3 ``?C ⊑ ∃r.D``; NF4 ``∃r.C ⊑ ?D``.
BOX2EL_SIDES = {
    "gci0": (1, (0,)),
    "gci1": (2, (0, 1)),
    "gci2": (0, ()),
    "gci3": (2, ()),
}

BOX2EL_METRICS = ("hits@1", "hits@10", "hits@100", "med", "mrr", "mr", "auc")


class NormalFormRankingRegime(EvaluationRegime):
    """Per-normal-form axiom ranking of Box\\ :sup:`2`\\ EL.

    For every test axiom of a normal form, candidate axioms are generated by replacing
    one atomic concept with every atomic concept of the candidate set: the superclass
    :math:`D` of :math:`C \\sqsubseteq D` (excluding :math:`C`), the superclass :math:`E`
    of :math:`C \\sqcap D \\sqsubseteq E` (excluding :math:`C` and :math:`D`), the
    subclass :math:`C` of :math:`C \\sqsubseteq \\exists r.D`, and the superclass
    :math:`D` of :math:`\\exists r.C \\sqsubseteq D`. Candidates are ranked by score
    (lower is better), ties broken by candidate position; there is no filtering of
    known positives ("raw" ranks). Hits@1/10/100, median rank, MRR, mean rank and the
    ROC AUC of :func:`~mowl.evaluation.ranking_metrics.auc_box2el` are reported per
    normal form and for the ranks of all normal forms combined.

    Disjointness axioms (:math:`C \\sqcap D \\sqsubseteq \\bot`) are not evaluated.

    :param normal_forms: Normal forms to evaluate, in mOWL naming (``gci0`` = NF1, ...,
        ``gci3`` = NF4).
    :param split: ``"test"`` (``dataset.testing``) or ``"valid"`` (``dataset.validation``).
    :param candidates: IRIs of the candidate classes. Default: all classes of the dataset
        (``dataset.classes``), as the reference ranks over every class of the ontology.
    :param scoring: ``"auto"`` (the centre-distance scores of Appendix F where mOWL has
        them for the model, otherwise the model's loss), ``"centre_distance"``,
        ``"loss"`` or a callable; see :func:`mowl.evaluation.el_scoring.resolve_scorer`.
    :param combined: Whether to report the ``"combined"`` subset.
    :param max_rows: Number of candidate axioms scored at once.
    """

    key = "box2el-normal-form-ranking"
    metrics = BOX2EL_METRICS

    def __init__(self, normal_forms=("gci0", "gci1", "gci2", "gci3"), split="test",
                 candidates=None, scoring="auto", combined=True, max_rows=2 ** 22):
        for nf in normal_forms:
            if nf not in BOX2EL_SIDES:
                raise ValueError(f"Unsupported normal form {nf!r}.")
        self.normal_forms = tuple(normal_forms)
        self.split = split
        self.candidates = candidates
        self.scoring = scoring
        self.combined = combined
        self.max_rows = max_rows
        self.subsets = self.normal_forms + (("combined",) if combined else ())
        #: Details of the last evaluation (scoring used, counts), for the result record.
        self.info = {}

    def _ontology(self, dataset):
        if self.split == "test":
            return dataset.testing
        if self.split == "valid":
            return dataset.validation
        raise ValueError(f"Unknown split {self.split!r}.")

    def candidate_iris(self, dataset):
        if self.candidates is not None:
            return list(self.candidates)
        return [c for c in dataset.classes.as_str]

    def evaluate(self, model, dataset):
        scorer, scoring_name = resolve_scorer(model, self.scoring)
        rows, skipped = el_rows(model, self._ontology(dataset))
        cands = candidate_indices(model, self.candidate_iris(dataset))
        results, all_ranks = {}, []
        counts = {}
        for nf in self.normal_forms:
            target, exclude = BOX2EL_SIDES[nf]
            nf_rows = rows.get(nf, th.zeros((0, 2 if nf == "gci0" else 3), dtype=th.long))
            ranks, _, kept = rank_queries(model, nf, nf_rows, target, cands, scorer,
                                          ties="ordinal", exclude_cols=exclude,
                                          max_rows=self.max_rows)
            ranks = ranks.tolist()
            counts[nf] = {"queries": int(kept.sum()), "dropped": int((~kept).sum())}
            all_ranks.extend(ranks)
            results[nf] = summarise_ranks(ranks, len(cands), hits=(1, 10, 100), auc="box2el")
        if self.combined:
            results["combined"] = summarise_ranks(all_ranks, len(cands), hits=(1, 10, 100),
                                                  auc="box2el")
        self.info = {"scoring": scoring_name, "num_candidates": int(len(cands)),
                     "skipped_axioms": skipped, "queries": counts}
        return results


class InferredSubsumptionRankingRegime(NormalFormRankingRegime):
    """"Approximating deductive reasoning" of Box\\ :sup:`2`\\ EL (Section 4.4): the model
    is trained on the full ontology and ranks the atomic subsumptions
    :math:`C \\sqsubseteq D` that an :math:`\\mathcal{EL}^{++}` reasoner infers from it
    but that are not asserted (90% test, 10% validation). The ranking is the NF1 ranking
    of :class:`NormalFormRankingRegime` (rank :math:`D` among all classes, excluding
    :math:`C`; raw ranks; Box2EL AUC). The test set is ``dataset.testing``.
    """

    key = "inferred-subsumption-ranking"

    def __init__(self, split="test", candidates=None, scoring="auto", max_rows=2 ** 22):
        super().__init__(normal_forms=("gci0",), split=split, candidates=candidates,
                         scoring=scoring, combined=False, max_rows=max_rows)
        self.subsets = ("all",)

    def evaluate(self, model, dataset):
        res = super().evaluate(model, dataset)
        return {"all": res["gci0"]}


class SubsumeeRankingRegime(EvaluationRegime):
    """Subsumption evaluation of EmEL++ (Mondal et al., AAAI-MAKE 2021, Section 4.4;
    reference ``Evaluating_HITS.py``): for every test axiom :math:`C \\sqsubseteq D`, all
    classes other than :math:`D` are ranked by the distance of their centre from the
    centre of :math:`D`, and the rank of :math:`C` is recorded (raw ranks, ties by
    position). Reported: Hits@1/10/100, median rank, 90th percentile rank and the ROC
    AUC of :func:`~mowl.evaluation.ranking_metrics.auc_rank_curve`.

    :param scoring: ``"auto"`` uses centre distances where mOWL has them for the model,
        otherwise the model's ``gci0`` loss for :math:`C \\sqsubseteq D`.
    """

    key = "emelpp-subsumee-ranking"
    metrics = ("hits@1", "hits@10", "hits@100", "auc", "med", "p90")
    subsets = ("all",)

    def __init__(self, split="test", candidates=None, scoring="auto", max_rows=2 ** 22):
        self.split = split
        self.candidates = candidates
        self.scoring = scoring
        self.max_rows = max_rows
        self.info = {}

    def evaluate(self, model, dataset):
        scorer, scoring_name = resolve_scorer(model, self.scoring)
        onto = dataset.testing if self.split == "test" else dataset.validation
        rows, skipped = el_rows(model, onto)
        iris = self.candidates if self.candidates is not None else dataset.classes.as_str
        cands = candidate_indices(model, iris)
        gci0 = rows.get("gci0", th.zeros((0, 2), dtype=th.long))
        ranks, _, kept = rank_queries(model, "gci0", gci0, 0, cands, scorer,
                                      ties="ordinal", exclude_cols=(1,),
                                      max_rows=self.max_rows)
        ranks = ranks.tolist()
        m = summarise_ranks(ranks, len(cands), hits=(1, 10, 100), auc="rank_curve")
        m["p90"] = float(np.percentile(ranks, 90)) if ranks else float("nan")
        self.info = {"scoring": scoring_name, "num_candidates": int(len(cands)),
                     "queries": int(kept.sum()), "skipped_axioms": skipped}
        return {"all": {k: m[k] for k in self.metrics}}


def mean_over_seeds(results):
    """Average a list of ``{subset: {metric: value}}`` dicts (the published numbers of
    Box2EL are means over 5 seeds)."""
    out = {}
    for subset in results[0]:
        out[subset] = {m: float(np.mean([r[subset][m] for r in results]))
                       for m in results[0][subset]}
    return out
