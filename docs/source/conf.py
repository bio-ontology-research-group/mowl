# The method catalogue, the training / evaluation regimes and the table of published
# benchmark results are rendered from the registries, so the documentation cannot drift
# from the code. The generated files are not committed (see .gitignore).
def _combinations_to_rst():
    """Which method is which combination of parts, and which parts can be named: generated
    from ``mowl.representation`` so that the page cannot drift from the registries."""
    from mowl.representation import (METHODS, METHOD_KINDS, REPRESENTATIONS, CLASS_MODELS,
                                     RELATION_MODELS, MEASURES)

    def names(values):
        return ", ".join(v.value for v in values)

    lines = [
        "Which method is which combination",
        "=================================",
        "",
        ".. This page is generated by docs/source/conf.py from mowl.representation.",
        "",
        "Every method below can be built from parts. ``ComposedEL(dataset, method=KEY)`` trains",
        "it from the parts, with the same losses as the method's own module. The columns name the",
        "parts as the catalogue states them (:doc:`/methods/catalogue` has the rest of the",
        "description). \"Trained on\" says what the method learns from: ``axioms`` are the",
        "normal-form axioms of an ontology, which ``ComposedEL`` trains; ``queries`` are query",
        "trees, trained by the query models of :mod:`mowl.models.query`.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 16 10 22 26 26",
        "",
        "   * - Method (key)",
        "     - Trained on",
        "     - A class is",
        "     - A relation is",
        "     - \"Inside\" is scored by",
    ]
    for key in sorted(METHODS):
        rep = REPRESENTATIONS.get(key)
        if rep is None:
            continue
        lines += [f"   * - ``{key}``",
                  f"     - {METHOD_KINDS.get(key, 'axioms')}",
                  f"     - {names(rep.classes)}",
                  f"     - {names(rep.relations)}",
                  f"     - {names(rep.measure)}"]
    lines += [
        "",
        "Names of parts that can be chosen freely",
        "----------------------------------------",
        "",
        "These are the names that ``ComposedEL(dataset, classes=..., relations=...,",
        "measure=...)`` accepts (and ``mowl.representation.compose``). A name is a plain string;",
        "see :doc:`combine` for how to use them.",
        "",
        "Class models",
        "    " + ", ".join(f"``{n}``" for n in sorted(CLASS_MODELS)),
        "Relation models",
        "    " + ", ".join(f"``{n}``" for n in sorted(RELATION_MODELS)),
        "Measures",
        "    " + ", ".join(f"``{n}``" for n in sorted(MEASURES)),
        ""]
    return "\n".join(lines)


def _write_generated_pages():
    from mowl.catalog import catalogue_to_rst, regimes_to_rst
    from mowl.benchmarks.report import published_to_rst

    here = os.path.dirname(os.path.abspath(__file__))
    pages = {
        os.path.join("methods", "catalogue.rst"): catalogue_to_rst(),
        os.path.join("methods", "regimes.rst"): regimes_to_rst(),
        os.path.join("benchmarks", "_published.rst"): published_to_rst(),
        os.path.join("representation", "combinations.rst"): _combinations_to_rst(),
    }
    for relative, text in pages.items():
        path = os.path.join(here, relative)
        if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(text)


_write_generated_pages()
